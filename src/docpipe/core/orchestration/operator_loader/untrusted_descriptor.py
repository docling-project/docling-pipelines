"""Lightweight descriptors for untrusted custom operators.

An operator uploaded through the API or fetched from an object store is untrusted: the API process must not
import it, because importing runs its module-level code. Discovery, listing, flow validation and factory refresh
therefore register a *descriptor* built from the AST data (``short_name``, ``category`` and the statically known
entries of ``get_metadata()``) instead of the imported class.

The real module is imported only when a node using the operator is constructed for execution, via
``UntrustedOperatorDescriptor.__new__``. That construction is the single seam where the isolation worker (task D.3)
takes over. Until then it stays in-process, and it is refused while a secret provider is registered, because
untrusted code must never share a process with secrets.
"""

import copy
from pathlib import Path
from typing import Any, ClassVar

from docpipe.core.constants.constants import DocpipeConstants
from docpipe.core.constants.operator_constants import OperatorConstants
from docpipe.core.operators.abstract_operator import AbstractOperator, OperatorCategory
from docpipe.core.orchestration.operator_loader.module_import import import_module_from_file
from docpipe.core.orchestration.operator_loader.ports.operator_source import OperatorInfo, TrustClass
from docpipe.core.orchestration.operator_loader.validator import OperatorValidator
from docpipe.exceptions.docpipe_exceptions import DocpipeException
from docpipe.integrations.secrets.secret_provider import has_registered_provider
from docpipe.utils.infrastructure.logging import get_logger

logger = get_logger(__name__)

NOT_PERMITTED_MESSAGE = (
    "not permitted: untrusted custom operator '%s' cannot run inside the API process while a secret provider is "
    "registered; it needs the process isolation boundary"
)


def untrusted_execution_permitted() -> bool:
    """Return True when untrusted operator code may be imported in this process.

    It may not while a secret provider is registered. Task D.3 replaces this with the ``custom_operators.isolation``
    setting and the worker process.
    """
    return not has_registered_provider()


class UntrustedOperatorDescriptor(AbstractOperator):
    """Stand-in registered in the operator factory for an untrusted operator.

    Subclasses are generated by ``build_untrusted_descriptor``; they carry the AST-derived data as class attributes.
    Instantiating one for flow validation never imports the uploaded file. Instantiating one for execution returns
    an instance of the real operator class, imported at that point only.
    """

    owner: str | None = DocpipeConstants.OWNER_CUSTOM
    trust_class: ClassVar[TrustClass] = TrustClass.UNTRUSTED
    operator_info: ClassVar[OperatorInfo]
    _real_class: ClassVar[type[AbstractOperator] | None] = None

    def __new__(cls, config: dict[str, Any]) -> Any:
        """Return a validation-only descriptor instance, or the real operator instance when executing."""
        if config.get(DocpipeConstants.VALIDATING_FLOW, False):
            return super().__new__(cls)
        if not untrusted_execution_permitted():
            raise DocpipeException(NOT_PERMITTED_MESSAGE % cls.operator_info.short_name, status_code=403)
        return cls._load_real_class()(config=config)

    @classmethod
    def _load_real_class(cls) -> type[AbstractOperator]:
        """Import the operator file and return the class the descriptor was built for."""
        if cls._real_class is not None:
            return cls._real_class
        info = cls.operator_info
        if info.source_file is None:
            raise DocpipeException(f"Untrusted operator '{info.short_name}' has no source file")
        logger.info("Importing untrusted operator '%s' for execution", info.short_name)
        module = import_module_from_file(file_path=Path(info.source_file))
        real_class = OperatorValidator.select_operator_class(module=module, operator_info=info)
        if real_class is None or getattr(real_class, "short_name", None) != info.short_name:
            raise DocpipeException(
                f"Operator file for '{info.short_name}' no longer defines that operator; refresh the operators"
            )
        cls._real_class = real_class
        return real_class

    def validate(self, errors: list[str], warnings: list[str], available_features: list[str]) -> None:
        """Validate without importing the uploaded file; only the trust-boundary check applies."""
        if not untrusted_execution_permitted():
            errors.append(NOT_PERMITTED_MESSAGE % self.operator_info.short_name)


def build_untrusted_descriptor(*, operator_info: OperatorInfo) -> type[AbstractOperator]:
    """Build the descriptor class for an untrusted operator from its AST-derived ``OperatorInfo``.

    Args:
        operator_info: Operator data read statically from the source file; must not require importing it

    Returns:
        A class usable wherever the factory expects an operator class, which never imports the source file until
        a node is constructed for execution
    """
    metadata: dict[str, Any] = {
        OperatorConstants.Misc.CATEGORY: operator_info.category,
        OperatorConstants.Misc.IS_OPERATOR_AVAILABLE: True,
        OperatorConstants.Misc.LABEL: operator_info.short_name,
        OperatorConstants.Config.FEATURES: {},
        OperatorConstants.Config.ATTRIBUTES: {},
    }
    metadata.update(copy.deepcopy(operator_info.static_metadata))

    def get_metadata() -> dict[str, Any]:
        return copy.deepcopy(metadata)

    namespace: dict[str, Any] = {
        "__module__": __name__,
        "__doc__": f"Descriptor of untrusted custom operator '{operator_info.short_name}' (not imported).",
        "short_name": operator_info.short_name,
        "category": OperatorCategory(operator_info.category),
        "operator_info": operator_info,
        "get_metadata": staticmethod(get_metadata),
        "_real_class": None,
    }
    return type(operator_info.name, (UntrustedOperatorDescriptor,), namespace)  # type: ignore[return-value]
