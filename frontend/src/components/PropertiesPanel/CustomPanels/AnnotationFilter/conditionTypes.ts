/**
 * Generates a collision-resistant ID for a new condition row.
 *
 * Uses `crypto.getRandomValues` for entropy rather than `Math.random` so that
 * IDs remain unique even when many conditions are added in rapid succession.
 *
 * @returns A string of the form `"cond-<timestamp>-<randomHex>"`.
 */
export function generateConditionId(): string {
  const bytes = new Uint8Array(8);
  globalThis.crypto.getRandomValues(bytes);
  const hex = Array.from(bytes).map((b) => b.toString(16).padStart(2, '0')).join('');
  return `cond-${Date.now()}-${hex}`;
}

/**
 * Converts a structured {@link Condition} into a human-readable display string.
 *
 * Used when rendering rows in the criteria table and the full-view tearsheet.
 *
 * @param condition - The condition to format.
 * @returns A string of the form `"<variable> <operator> <value>"`.
 *
 * @example
 * ```ts
 * conditionToText({ id: '…', variable: 'lang_score', operator: '>=', value: '0.3' })
 * // → "lang_score >= 0.3"
 * ```
 */
export function conditionToText(condition: Condition): string {
  return `${condition.variable} ${condition.operator} ${condition.value}`;
}

/**
 * Returns `true` when `value` is a valid JSON string.
 * Used to validate condition values for `json`-typed features.
 *
 * @param value - The string to test.
 */
export function isValidJSON(value: string): boolean {
  try {
    JSON.parse(value);
    return true;
  } catch {
    return false;
  }
}
