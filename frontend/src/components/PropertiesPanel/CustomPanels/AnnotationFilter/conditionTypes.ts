/**
 * A single filter condition in the Simple-mode condition builder.
 *
 * Conditions are stored inside {@link CriteriaJson.criteria_list} and are
 * mapped one-to-one with rows in the condition builder UI.
 */
export interface Condition {
  /** Stable unique identifier generated by {@link generateConditionId}. */
  id: string;
  /** Feature/column name selected from the upstream node's `input_features`. */
  variable: string;
  /**
   * SQL comparison operator (e.g. `==`, `>=`, `like`).
   * One of the `value` fields in {@link SQL_OPERATORS}.
   */
  operator: string;
  /** Right-hand side value as a string; empty string for null-check operators. */
  value: string;
}

/**
 * The structured object written to the `criteria_json` Elyra parameter in
 * Simple mode.
 *
 * @example
 * ```json
 * {
 *   "logical_operator": "AND",
 *   "criteria_list": [
 *     { "id": "cond-...", "variable": "lang_score", "operator": ">=", "value": "0.3" }
 *   ]
 * }
 * ```
 */
export interface CriteriaJson {
  /** How multiple conditions are combined — `"AND"` or `"OR"`. */
  logical_operator: string;
  /** Ordered list of individual filter conditions. */
  criteria_list: Condition[];
}

